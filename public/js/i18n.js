export function setLang(l) { store.set('lang', l); location.reload(); }

export function tr(key, vars = []) {
  let s = lang === 'en' ? (EN[key] ?? key) : key;
  vars.forEach((v, i) => { s = s.replace(`{${i}}`, v); });
  return s;
}

